import {
  PAYMENT_TRANSACTION_STATUS,
  type PaymentTransactionStatusCode,
} from '../enum/payments.enum.js';

const ALLOWED_TRANSITIONS: Readonly<
  Record<PaymentTransactionStatusCode, ReadonlySet<PaymentTransactionStatusCode>>
> = {
  [PAYMENT_TRANSACTION_STATUS.PENDING]: new Set([
    PAYMENT_TRANSACTION_STATUS.PENDING,
    PAYMENT_TRANSACTION_STATUS.PROCESSING,
    PAYMENT_TRANSACTION_STATUS.SUCCEEDED,
    PAYMENT_TRANSACTION_STATUS.FAILED,
    PAYMENT_TRANSACTION_STATUS.CANCELLED,
    PAYMENT_TRANSACTION_STATUS.EXPIRED,
  ]),
  [PAYMENT_TRANSACTION_STATUS.PROCESSING]: new Set([
    PAYMENT_TRANSACTION_STATUS.PROCESSING,
    PAYMENT_TRANSACTION_STATUS.SUCCEEDED,
    PAYMENT_TRANSACTION_STATUS.FAILED,
    PAYMENT_TRANSACTION_STATUS.CANCELLED,
    PAYMENT_TRANSACTION_STATUS.EXPIRED,
  ]),
  [PAYMENT_TRANSACTION_STATUS.SUCCEEDED]: new Set([
    PAYMENT_TRANSACTION_STATUS.SUCCEEDED,
    PAYMENT_TRANSACTION_STATUS.PARTIALLY_REFUNDED,
    PAYMENT_TRANSACTION_STATUS.REFUNDED,
  ]),
  [PAYMENT_TRANSACTION_STATUS.PARTIALLY_REFUNDED]: new Set([
    PAYMENT_TRANSACTION_STATUS.PARTIALLY_REFUNDED,
    PAYMENT_TRANSACTION_STATUS.REFUNDED,
  ]),
  [PAYMENT_TRANSACTION_STATUS.FAILED]: new Set([PAYMENT_TRANSACTION_STATUS.FAILED]),
  [PAYMENT_TRANSACTION_STATUS.CANCELLED]: new Set([PAYMENT_TRANSACTION_STATUS.CANCELLED]),
  [PAYMENT_TRANSACTION_STATUS.EXPIRED]: new Set([PAYMENT_TRANSACTION_STATUS.EXPIRED]),
  [PAYMENT_TRANSACTION_STATUS.REFUNDED]: new Set([PAYMENT_TRANSACTION_STATUS.REFUNDED]),
};

export function canTransitionPaymentStatus(
  fromStatus: PaymentTransactionStatusCode,
  toStatus: PaymentTransactionStatusCode,
): boolean {
  const allowed = ALLOWED_TRANSITIONS[fromStatus];
  return Boolean(allowed?.has(toStatus));
}

export function isTerminalPaymentStatus(status: PaymentTransactionStatusCode): boolean {
  return (
    status === PAYMENT_TRANSACTION_STATUS.FAILED ||
    status === PAYMENT_TRANSACTION_STATUS.CANCELLED ||
    status === PAYMENT_TRANSACTION_STATUS.EXPIRED ||
    status === PAYMENT_TRANSACTION_STATUS.REFUNDED
  );
}

export function isRefundablePaymentStatus(status: PaymentTransactionStatusCode): boolean {
  return (
    status === PAYMENT_TRANSACTION_STATUS.SUCCEEDED ||
    status === PAYMENT_TRANSACTION_STATUS.PARTIALLY_REFUNDED
  );
}
