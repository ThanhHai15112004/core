import { z } from 'zod';

export const settingGroupResponseSchema = z.object({
  id: z.number().int(),
  code: z.string(),
  module: z.string(),
  name: z.string(),
  description: z.string().nullable(),
  icon: z.string().nullable(),
  sortOrder: z.number().int(),
  isSystem: z.boolean(),
  status: z.number().int(),
  statusName: z.enum(['ACTIVE', 'INACTIVE']),
  settingCount: z.number().int(),
});

export const settingScopeOverrideResponseSchema = z.object({
  id: z.number().int(),
  settingKey: z.string(),
  environment: z.string(),
  organizationUnitId: z.number().int().nullable(),
  scopeKey: z.string(),
  value: z.unknown(),
  isSensitive: z.boolean(),
  isEncrypted: z.boolean(),
  hasValue: z.boolean(),
  updatedBy: z.number().int().nullable(),
  reason: z.string().nullable(),
  updatedAt: z.string(),
});

export const systemSettingResponseSchema = z.object({
  id: z.number().int(),
  key: z.string(),
  groupCode: z.string(),
  module: z.string(),
  namespace: z.string(),
  name: z.string(),
  description: z.string().nullable(),
  valueType: z.number().int(),
  valueTypeName: z.enum(['TEXT', 'NUMBER', 'BOOLEAN', 'JSON']),
  value: z.unknown(),
  globalValue: z.unknown(),
  defaultValue: z.unknown(),
  validationRules: z.record(z.string(), z.unknown()).nullable(),
  isSensitive: z.boolean(),
  isEncrypted: z.boolean(),
  hasValue: z.boolean(),
  allowUnitOverride: z.boolean(),
  isSystem: z.boolean(),
  sortOrder: z.number().int(),
  status: z.number().int(),
  statusName: z.enum(['ACTIVE', 'INACTIVE']),
  resolvedSource: z.string(),
  resolvedEnvironment: z.string(),
  resolvedOrganizationUnitId: z.number().int().nullable(),
  scopeOverrides: z.array(settingScopeOverrideResponseSchema),
  updatedBy: z.number().int().nullable(),
  updatedAt: z.string(),
});

export const resolvedSettingResponseSchema = z.object({
  key: z.string(),
  groupCode: z.string(),
  module: z.string(),
  namespace: z.string(),
  name: z.string(),
  description: z.string().nullable(),
  valueType: z.number().int(),
  valueTypeName: z.enum(['TEXT', 'NUMBER', 'BOOLEAN', 'JSON']),
  value: z.unknown(),
  defaultValue: z.unknown(),
  isSensitive: z.boolean(),
  isEncrypted: z.boolean(),
  hasValue: z.boolean(),
  allowUnitOverride: z.boolean(),
  isSystem: z.boolean(),
  resolvedSource: z.string(),
  resolvedEnvironment: z.string(),
  resolvedOrganizationUnitId: z.number().int().nullable(),
  fromCache: z.boolean(),
});

export const settingHistoryResponseSchema = z.object({
  id: z.number().int(),
  settingKey: z.string(),
  environment: z.string(),
  organizationUnitId: z.number().int().nullable(),
  valueType: z.number().int(),
  valueTypeName: z.enum(['TEXT', 'NUMBER', 'BOOLEAN', 'JSON']),
  oldValue: z.unknown(),
  newValue: z.unknown(),
  actorUserId: z.number().int().nullable(),
  actorIdentifier: z.string().nullable(),
  reason: z.string().nullable(),
  ipAddress: z.string().nullable(),
  userAgent: z.string().nullable(),
  requestId: z.string().nullable(),
  correlationId: z.string().nullable(),
  createdAt: z.string(),
});

export const syncSettingsResultResponseSchema = z.object({
  syncedModules: z.array(z.string()),
  totalGroups: z.number().int(),
  totalSettings: z.number().int(),
  totalEnvironmentOverrides: z.number().int(),
});
